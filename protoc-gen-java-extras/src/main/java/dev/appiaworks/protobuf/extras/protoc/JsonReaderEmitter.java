package dev.appiaworks.protobuf.extras.protoc;

import com.google.protobuf.Descriptors.Descriptor;
import com.google.protobuf.Descriptors.FieldDescriptor;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

/**
 * Writes the {@code mergeJson(JsonParser)} method inserted into a generated {@code Builder}, and
 * the descriptor holder it reads through, inserted into the message class: the message read from
 * proto JSON through its own setters, field by field, under the strict rules every
 * {@code ProtoJson} parse follows.
 *
 * <p>The method is a loop over the object's fields with a {@code switch} on the name (the JSON
 * name and the proto name both match, the first field wins a tie), and for each field the read
 * protoc's setters need: a scalar through {@code StrictScalars.read}, which does every check and
 * coercion the compiled parser does; a message through {@code GeneratedJson.message}, which asks
 * the dialect for a codec and then the nested builder for its own {@code mergeJson}; a repeated
 * field as a loop over an array, a map as a loop over an object. An unknown field is skipped, a
 * JSON null leaves a field unset (except {@code google.protobuf.Value}, where null is a value).
 *
 * <p>Same gate as {@link JsonWriterEmitter#canWrite}: a message reaching {@code google.protobuf.Any}
 * or a proto2 group gets no reader.
 */
final class JsonReaderEmitter {

    private JsonReaderEmitter() {}

    private static final String GENERATED_JSON = "dev.appiaworks.protobuf.extras.GeneratedJson";
    private static final String STRICT = "dev.appiaworks.protobuf.extras.serde.StrictScalars";
    private static final String FD = "com.google.protobuf.Descriptors.FieldDescriptor";
    private static final String EVD = "com.google.protobuf.Descriptors.EnumValueDescriptor";

    /** The descriptor holder, for the message's class scope: the Builder reads through it. */
    static String holder() {
        return """

                /** The fields the generated mergeJson reads through, in declaration order. */
                private static final class JsonFields {
                  static final %1$s[] F = %2$s.fields(getDescriptor());
                  static final %1$s[] MV = %2$s.mapValueFields(F);
                }
                """.formatted(FD, GENERATED_JSON);
    }

    /** The method, for the Builder scope of {@code message}. */
    static String mergeJson(Descriptor message) {
        StringBuilder out = new StringBuilder();
        out.append("""

                /**
                 * Reads one JSON object into this builder: every field by its JSON or proto name, under the
                 * strict rules of {@code ProtoJson}, in the dialect in force. Generated by
                 * protoc-gen-java-extras; {@code ProtoJson.parse} reads through it.
                 */
                @java.lang.Override
                public Builder mergeJson(com.fasterxml.jackson.core.JsonParser p) throws java.io.IOException {
                  %s.expectObject(p, getDescriptorForType());
                  while (p.nextToken() != com.fasterxml.jackson.core.JsonToken.END_OBJECT) {
                    java.lang.String name = p.currentName();
                    p.nextToken();
                    switch (name) {
                """.formatted(GENERATED_JSON));
        Set<String> taken = new HashSet<>();
        List<FieldDescriptor> fields = message.getFields();
        for (int i = 0; i < fields.size(); i++) {
            FieldDescriptor fd = fields.get(i);
            List<String> labels = labels(fd, taken);
            if (labels.isEmpty()) continue;
            out.append("      case ");
            for (int l = 0; l < labels.size(); l++) {
                if (l > 0) out.append(", ");
                out.append('"').append(literal(labels.get(l))).append('"');
            }
            out.append(" -> {\n");
            field(out, message, fd, i);
            out.append("      }\n");
        }
        out.append("""
                      default -> p.skipChildren();
                    }
                  }
                  return this;
                }
                """);
        return out.toString();
    }

    /** The case labels for a field: JSON name and proto name, minus any an earlier field took. */
    private static List<String> labels(FieldDescriptor fd, Set<String> taken) {
        List<String> labels = new java.util.ArrayList<>(2);
        if (taken.add(fd.getJsonName())) labels.add(fd.getJsonName());
        if (!fd.getName().equals(fd.getJsonName()) && taken.add(fd.getName())) labels.add(fd.getName());
        return labels;
    }

    private static void field(StringBuilder out, Descriptor message, FieldDescriptor fd, int index) {
        String name = JavaNames.accessorName(message, fd);
        String f = "JsonFields.F[" + index + "]";
        String indent = "        ";
        // JSON null leaves a field unset, except google.protobuf.Value, where null is a value.
        boolean acceptsNull = !fd.isRepeated() && isValue(fd);
        if (!acceptsNull) {
            out.append(indent)
                    .append("if (p.currentToken() == com.fasterxml.jackson.core.JsonToken.VALUE_NULL) break;\n");
        }
        if (fd.isMapField()) {
            map(out, indent, fd, name, f, "JsonFields.MV[" + index + "]");
        } else if (fd.isRepeated()) {
            out.append(indent)
                    .append(GENERATED_JSON)
                    .append(".expectArray(p, ")
                    .append(f)
                    .append(");\n");
            out.append(indent).append("while (p.nextToken() != com.fasterxml.jackson.core.JsonToken.END_ARRAY) {\n");
            value(out, indent + "  ", fd, f, "add" + name, "add" + name + "Value", "add" + name + "Builder()");
            out.append(indent).append("}\n");
        } else {
            value(out, indent, fd, f, "set" + name, "set" + name + "Value", "get" + name + "Builder()");
        }
    }

    /**
     * One value's read into the builder. {@code set} and {@code setNumber} name the setter and,
     * for an open enum, the number setter; {@code builder} the expression giving a nested
     * builder for a message-typed field.
     */
    private static void value(
            StringBuilder out,
            String indent,
            FieldDescriptor fd,
            String f,
            String set,
            String setNumber,
            String builder) {
        if (fd.getType() == FieldDescriptor.Type.MESSAGE) {
            out.append(indent)
                    .append(GENERATED_JSON)
                    .append(".message(p, ")
                    .append(f)
                    .append(", ")
                    .append(builder)
                    .append(");\n");
            return;
        }
        out.append(indent)
                .append("java.lang.Object v = ")
                .append(STRICT)
                .append(".read(p, ")
                .append(f)
                .append(");\n");
        if (fd.getType() == FieldDescriptor.Type.ENUM) {
            out.append(indent).append("if (v != null) ");
            if (fd.getEnumType().isClosed()) {
                out.append(set)
                        .append("(")
                        .append(JavaNames.javaClassName(fd.getEnumType()))
                        .append(".forNumber(((")
                        .append(EVD)
                        .append(") v).getNumber()));\n");
            } else {
                out.append(setNumber).append("(((").append(EVD).append(") v).getNumber());\n");
            }
            return;
        }
        out.append(indent)
                .append("if (v != null) ")
                .append(set)
                .append("((")
                .append(boxed(fd))
                .append(") v);\n");
    }

    /** A map field: a loop over the JSON object's entries, each key and value as the entry's types. */
    private static void map(StringBuilder out, String indent, FieldDescriptor fd, String name, String f, String mv) {
        FieldDescriptor key = fd.getMessageType().findFieldByNumber(1);
        FieldDescriptor value = fd.getMessageType().findFieldByNumber(2);
        out.append(indent)
                .append(GENERATED_JSON)
                .append(".expectMap(p, ")
                .append(f)
                .append(");\n");
        out.append(indent).append("while (p.nextToken() != com.fasterxml.jackson.core.JsonToken.END_OBJECT) {\n");
        String inner = indent + "  ";
        out.append(inner)
                .append(boxed(key))
                .append(" key = (")
                .append(boxed(key))
                .append(") ")
                .append(GENERATED_JSON)
                .append(".mapKey(")
                .append(f)
                .append(", p.currentName());\n");
        out.append(inner).append("p.nextToken();\n");
        if (value.getType() == FieldDescriptor.Type.MESSAGE) {
            String type = JavaNames.javaClassName(value.getMessageType());
            out.append(inner).append(type).append(".Builder vb = ").append(type).append(".newBuilder();\n");
            out.append(inner)
                    .append(GENERATED_JSON)
                    .append(".message(p, ")
                    .append(mv)
                    .append(", vb);\n");
            out.append(inner).append("put").append(name).append("(key, vb.build());\n");
        } else {
            out.append(inner)
                    .append("java.lang.Object v = ")
                    .append(STRICT)
                    .append(".read(p, ")
                    .append(mv)
                    .append(");\n");
            if (value.getType() == FieldDescriptor.Type.ENUM) {
                out.append(inner).append("if (v != null) ");
                if (value.getEnumType().isClosed()) {
                    out.append("put")
                            .append(name)
                            .append("(key, ")
                            .append(JavaNames.javaClassName(value.getEnumType()))
                            .append(".forNumber(((")
                            .append(EVD)
                            .append(") v).getNumber()));\n");
                } else {
                    out.append("put")
                            .append(name)
                            .append("Value(key, ((")
                            .append(EVD)
                            .append(") v).getNumber());\n");
                }
            } else {
                out.append(inner)
                        .append("if (v != null) put")
                        .append(name)
                        .append("(key, (")
                        .append(boxed(value))
                        .append(") v);\n");
            }
        }
        out.append(indent).append("}\n");
    }

    /** The boxed Java type StrictScalars.read returns for a scalar field, which the setter unboxes. */
    private static String boxed(FieldDescriptor fd) {
        return switch (fd.getType()) {
            case STRING -> "java.lang.String";
            case BYTES -> "com.google.protobuf.ByteString";
            case INT32, SINT32, SFIXED32, UINT32, FIXED32 -> "java.lang.Integer";
            case INT64, SINT64, SFIXED64, UINT64, FIXED64 -> "java.lang.Long";
            case FLOAT -> "java.lang.Float";
            case DOUBLE -> "java.lang.Double";
            case BOOL -> "java.lang.Boolean";
            default -> throw new IllegalArgumentException("Unsupported scalar type " + fd.getType() + " on " + fd);
        };
    }

    private static boolean isValue(FieldDescriptor fd) {
        return fd.getType() == FieldDescriptor.Type.MESSAGE
                && "google.protobuf.Value".equals(fd.getMessageType().getFullName());
    }

    private static String literal(String text) {
        StringBuilder b = new StringBuilder(text.length());
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            switch (c) {
                case '"' -> b.append("\\\"");
                case '\\' -> b.append("\\\\");
                default -> {
                    if (c < 0x20 || c > 0x7e) b.append(String.format("\\u%04x", (int) c));
                    else b.append(c);
                }
            }
        }
        return b.toString();
    }
}
