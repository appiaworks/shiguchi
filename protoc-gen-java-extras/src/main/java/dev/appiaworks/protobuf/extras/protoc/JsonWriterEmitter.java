package dev.appiaworks.protobuf.extras.protoc;

import com.google.protobuf.Descriptors.Descriptor;
import com.google.protobuf.Descriptors.EnumDescriptor;
import com.google.protobuf.Descriptors.FieldDescriptor;
import java.util.HashSet;
import java.util.Set;

/**
 * Writes the {@code writeJson(JsonGenerator)} method inserted into a generated message class:
 * the message as proto JSON through its own getters, field by field, in the dialect in force
 * at run time.
 *
 * <p>The method is the message's descriptor read out as straight-line Java: for every field,
 * the presence check protoc generated, the JSON name, and the value through the accessor protoc
 * generated. A repeated field is a counted loop, a map a loop over its entries, a 64-bit integer
 * goes through {@code ProtoMapConverter} (a string, or a number when the dialect says so), a
 * well-known type through {@code ProtoWkt}, any other message through {@code GeneratedJson},
 * which asks the dialect for a codec and then the value for its own {@code writeJson}. Nothing
 * here decides how a value looks; that stays in {@code protobuf-java-extras}, where the other
 * paths decide it too.
 *
 * <p>A message that reaches {@code google.protobuf.Any} or a proto2 group gets no method, as
 * the writers generated at run time refuse those too.
 */
final class JsonWriterEmitter {

    private JsonWriterEmitter() {}

    private static final String GENERATED_JSON = "dev.appiaworks.protobuf.extras.GeneratedJson";
    private static final String PROTO_WKT = "dev.appiaworks.protobuf.extras.serde.ProtoWkt";
    private static final String CONVERTER = "dev.appiaworks.protobuf.extras.serde.ProtoMapConverter";

    /** The {@code google.protobuf} types whose JSON is one value whatever the dialect: written by ProtoWkt directly. */
    private static final Set<String> FIXED_WKT = Set.of(
            "google.protobuf.Timestamp",
            "google.protobuf.Duration",
            "google.protobuf.FieldMask",
            "google.protobuf.Struct",
            "google.protobuf.Value",
            "google.protobuf.ListValue",
            "google.protobuf.DoubleValue",
            "google.protobuf.FloatValue",
            "google.protobuf.Int64Value",
            "google.protobuf.UInt64Value",
            "google.protobuf.Int32Value",
            "google.protobuf.UInt32Value",
            "google.protobuf.BoolValue",
            "google.protobuf.StringValue",
            "google.protobuf.BytesValue");

    /** Whether the message can carry a writer: nothing it reaches is an Any or a group. */
    static boolean canWrite(Descriptor message) {
        return !reachesAnyOrGroup(message, new HashSet<>());
    }

    private static boolean reachesAnyOrGroup(Descriptor d, Set<Descriptor> visited) {
        if (!visited.add(d)) return false;
        for (FieldDescriptor fd : d.getFields()) {
            if (fd.getType() == FieldDescriptor.Type.GROUP) return true;
            if (fd.getType() != FieldDescriptor.Type.MESSAGE) continue;
            Descriptor type = fd.getMessageType();
            if ("google.protobuf.Any".equals(type.getFullName())) return true;
            if (reachesAnyOrGroup(type, visited)) return true;
        }
        return false;
    }

    /** The method, for the class scope of {@code message}; call {@link #canWrite} first. */
    static String writeJson(Descriptor message) {
        StringBuilder out = new StringBuilder();
        out.append("""

                /**
                 * This message as proto JSON: every field, lowerCamelCase names, 64-bit integers as
                 * strings, in the dialect in force ({@code ProtoJsonMapping}). Generated by
                 * protoc-gen-java-extras; {@code ProtoJson} and the gateway print through it.
                 */
                @java.lang.Override
                public void writeJson(com.fasterxml.jackson.core.JsonGenerator gen) throws java.io.IOException {
                  gen.writeStartObject();
                """);
        for (FieldDescriptor fd : message.getFields()) {
            field(out, message, fd);
        }
        out.append("""
                  gen.writeEndObject();
                }
                """);
        return out.toString();
    }

    private static void field(StringBuilder out, Descriptor message, FieldDescriptor fd) {
        String name = JavaNames.accessorName(message, fd);
        boolean guarded = !fd.isRepeated() && fd.hasPresence();
        String indent = "  ";
        if (guarded) {
            out.append("  if (has").append(name).append("()) {\n");
            indent = "    ";
        }
        out.append(indent)
                .append("gen.writeFieldName(\"")
                .append(literal(fd.getJsonName()))
                .append("\");\n");
        if (fd.isMapField()) {
            map(out, indent, fd, name);
        } else if (fd.isRepeated()) {
            out.append(indent).append("gen.writeStartArray();\n");
            out.append(indent)
                    .append("for (int i = 0, count = get")
                    .append(name)
                    .append("Count(); i < count; i++) {\n");
            value(out, indent + "  ", fd, "get" + name + "(i)", "get" + name + "Value(i)");
            out.append(indent).append("}\n");
            out.append(indent).append("gen.writeEndArray();\n");
        } else {
            value(out, indent, fd, "get" + name + "()", "get" + name + "Value()");
        }
        if (guarded) out.append("  }\n");
    }

    /** A map field: the entries of the typed map, keys as the strings proto JSON uses. */
    private static void map(StringBuilder out, String indent, FieldDescriptor fd, String name) {
        FieldDescriptor key = fd.getMessageType().findFieldByNumber(1);
        FieldDescriptor value = fd.getMessageType().findFieldByNumber(2);
        boolean openEnum = value.getType() == FieldDescriptor.Type.ENUM
                && !value.getEnumType().isClosed();
        // An open enum's numbers come from the Value map, so an unknown one is still a number.
        String accessor = "get" + name + (openEnum ? "ValueMap()" : "Map()");
        out.append(indent).append("gen.writeStartObject();\n");
        out.append(indent)
                .append("for (java.util.Map.Entry<?, ?> entry : ")
                .append(accessor)
                .append(".entrySet()) {\n");
        String inner = indent + "  ";
        out.append(inner).append("gen.writeFieldName(").append(mapKey(key)).append(");\n");
        String cast = "(" + boxed(value) + ") entry.getValue()";
        if (value.getType() == FieldDescriptor.Type.ENUM) {
            if (openEnum) {
                enumNumber(out, inner, value.getEnumType(), cast);
            } else {
                out.append(inner).append("gen.writeString(((java.lang.Enum<?>) entry.getValue()).name());\n");
            }
        } else {
            value(out, inner, value, cast, null);
        }
        out.append(indent).append("}\n");
        out.append(indent).append("gen.writeEndObject();\n");
    }

    private static String mapKey(FieldDescriptor key) {
        return switch (key.getType()) {
            case STRING -> "(java.lang.String) entry.getKey()";
            case UINT32, FIXED32 -> "java.lang.Integer.toUnsignedString((java.lang.Integer) entry.getKey())";
            case UINT64, FIXED64 -> "java.lang.Long.toUnsignedString((java.lang.Long) entry.getKey())";
            default -> "java.lang.String.valueOf(entry.getKey())";
        };
    }

    /** The boxed Java type a map's value has in the typed map, for the cast. */
    private static String boxed(FieldDescriptor value) {
        return switch (value.getType()) {
            case STRING -> "java.lang.String";
            case BYTES -> "com.google.protobuf.ByteString";
            case INT32, SINT32, SFIXED32, UINT32, FIXED32, ENUM -> "java.lang.Integer";
            case INT64, SINT64, SFIXED64, UINT64, FIXED64 -> "java.lang.Long";
            case FLOAT -> "java.lang.Float";
            case DOUBLE -> "java.lang.Double";
            case BOOL -> "java.lang.Boolean";
            case MESSAGE -> "com.google.protobuf.Message";
            default -> throw new IllegalArgumentException("Unsupported map value type " + value.getType());
        };
    }

    /**
     * One value's write. {@code expr} is the value as the accessor returns it; {@code number},
     * for an enum field, the expression giving its number ({@code getXxxValue()}).
     */
    private static void value(StringBuilder out, String indent, FieldDescriptor fd, String expr, String number) {
        switch (fd.getType()) {
            case MESSAGE -> {
                String helper = FIXED_WKT.contains(fd.getMessageType().getFullName())
                        ? PROTO_WKT + ".writeJson"
                        : GENERATED_JSON + ".message";
                out.append(indent).append(helper).append("(gen, ").append(expr).append(");\n");
            }
            case STRING ->
                out.append(indent).append("gen.writeString(").append(expr).append(");\n");
            case BYTES ->
                out.append(indent)
                        .append("gen.writeString(java.util.Base64.getEncoder().encodeToString((")
                        .append(expr)
                        .append(").toByteArray()));\n");
            case INT32, SINT32, SFIXED32, FLOAT, DOUBLE ->
                out.append(indent).append("gen.writeNumber(").append(expr).append(");\n");
            case UINT32, FIXED32 ->
                out.append(indent).append("gen.writeNumber((").append(expr).append(") & 0xFFFFFFFFL);\n");
            case INT64, SINT64, SFIXED64 ->
                out.append(indent)
                        .append(CONVERTER)
                        .append(".writeInt64(gen, ")
                        .append(expr)
                        .append(");\n");
            case UINT64, FIXED64 ->
                out.append(indent)
                        .append(CONVERTER)
                        .append(".writeUInt64(gen, ")
                        .append(expr)
                        .append(");\n");
            case BOOL ->
                out.append(indent).append("gen.writeBoolean(").append(expr).append(");\n");
            case ENUM -> {
                if (fd.getEnumType().isClosed()) {
                    // proto2: the constant is always a known one, with a name
                    out.append(indent).append("gen.writeString((").append(expr).append(").name());\n");
                } else {
                    enumNumber(out, indent, fd.getEnumType(), number);
                }
            }
            default -> throw new IllegalArgumentException("Unsupported field type " + fd.getType() + " on " + fd);
        }
    }

    /** An open enum from its number: the constant's name, or the number when the class has no constant for it. */
    private static void enumNumber(StringBuilder out, String indent, EnumDescriptor type, String number) {
        String enumClass = JavaNames.javaClassName(type);
        out.append(indent).append("{\n");
        out.append(indent).append("  int number = ").append(number).append(";\n");
        out.append(indent)
                .append("  ")
                .append(GENERATED_JSON)
                .append(".enumValue(gen, ")
                .append(enumClass)
                .append(".forNumber(number), number);\n");
        out.append(indent).append("}\n");
    }

    /** A JSON name as a Java string literal's content: protoc keeps them to letters and digits, but be safe. */
    private static String literal(String text) {
        StringBuilder b = new StringBuilder(text.length());
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            switch (c) {
                case '"' -> b.append("\\\"");
                case '\\' -> b.append("\\\\");
                default -> {
                    if (c < 0x20 || c > 0x7e) b.append(String.format("\\u%04x", (int) c));
                    else b.append(c);
                }
            }
        }
        return b.toString();
    }
}
