plugins {
    // Compiles src/test/proto: the Tier 1 typed writer is tested against real generated classes.
    id("com.google.protobuf")
}

// The proto JSON serde and type converters as a plain-Java library: protobuf and Jackson's
// streaming API, nothing else. No Spring, no gRPC, no Reactor — shiguchi-core adds those on
// top. Keep it that way: a dependency added here lands on every consumer who wanted only this.
dependencies {
    api(libs.protobuf.java)
    // com.google.type.* appears in ProtoTypes' signatures.
    api(libs.proto.common.protos)
    // JsonGenerator appears in ProtoMapConverter's and ProtoWkt's signatures.
    api("com.fasterxml.jackson.core:jackson-core:2.22.3")
    implementation(libs.protobuf.java.util)

    // The Spring BOM versions JUnit and AssertJ, for tests alone.
    testImplementation(platform(libs.spring.boot.bom))
    testImplementation("org.junit.jupiter:junit-jupiter")
    testImplementation("org.assertj:assertj-core")
    // Tree-equal JSON comparisons in the parity tests; the library itself never needs databind.
    testImplementation("com.fasterxml.jackson.core:jackson-databind")
    // The compiled serializers are generated by the ClassFile-API module (Java 25+); its parity
    // tests live here, next to the plans and contracts they implement.
    testRuntimeOnly(project(":protobuf-java-extras-classfile"))
    testRuntimeOnly("org.junit.platform:junit-platform-launcher")
}

protobuf {
    protoc { artifact = "com.google.protobuf:protoc:${libs.versions.protobuf.get()}" }
}
